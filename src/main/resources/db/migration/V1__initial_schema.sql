-- BastionVault schema v1 (PostgreSQL). Kept to portable SQL so the H2 test database runs it too.

-- Singleton row (id = 1): key-derivation parameters and the wrapped data encryption key (DEK).
-- The DEK itself is never stored; only copies encrypted ("wrapped") by each unlock method.
CREATE TABLE vault_config (
    id                  SMALLINT PRIMARY KEY,
    crypto_version      INTEGER                  NOT NULL,
    kdf_algorithm       VARCHAR(32)              NOT NULL,
    kdf_iterations      INTEGER                  NOT NULL,
    kdf_salt            BYTEA                    NOT NULL,
    dek_by_password     BYTEA                    NOT NULL,
    dek_by_recovery     BYTEA                    NOT NULL,
    dek_by_unseal_key   BYTEA,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT vault_config_singleton CHECK (id = 1)
);

-- Human administrators (UI login). Independent from the master password that unseals the vault.
CREATE TABLE admin_users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(64)              NOT NULL UNIQUE,
    password_hash   VARCHAR(100)             NOT NULL,
    enabled         BOOLEAN                  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at   TIMESTAMP WITH TIME ZONE
);

-- Encrypted secrets. value_blob = AES-256-GCM nonce || ciphertext || tag, with (group, key) as AAD.
CREATE TABLE secrets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_group   VARCHAR(128)             NOT NULL,
    secret_key  VARCHAR(128)             NOT NULL,
    value_blob  BYTEA                    NOT NULL,
    enc_version INTEGER                  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by  VARCHAR(128)             NOT NULL,
    CONSTRAINT secrets_group_key_uq UNIQUE (app_group, secret_key)
);

-- Machine identities.
CREATE TABLE api_clients (
    client_id     VARCHAR(64)              PRIMARY KEY,
    display_name  VARCHAR(128)             NOT NULL,
    secret_hash   VARCHAR(100)             NOT NULL,
    active        BOOLEAN                  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at  TIMESTAMP WITH TIME ZONE
);

-- What each client may do. Deny by default: no matching rule = no access.
CREATE TABLE policy_rules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id      VARCHAR(64)  NOT NULL REFERENCES api_clients (client_id) ON DELETE CASCADE,
    group_pattern  VARCHAR(128) NOT NULL,
    can_read       BOOLEAN      NOT NULL,
    can_write      BOOLEAN      NOT NULL,
    CONSTRAINT policy_rules_client_pattern_uq UNIQUE (client_id, group_pattern)
);

-- Long-lived API keys (for External Secrets Operator, CI). Token format: bvk_<key_id>_<secret>.
-- Only SHA-256(secret) is stored; the secret is 256 random bits so a fast hash is sufficient.
CREATE TABLE api_keys (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     VARCHAR(64)              NOT NULL REFERENCES api_clients (client_id) ON DELETE CASCADE,
    key_id        VARCHAR(16)              NOT NULL UNIQUE,
    secret_hash   BYTEA                    NOT NULL,
    name          VARCHAR(128)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at    TIMESTAMP WITH TIME ZONE,
    last_used_at  TIMESTAMP WITH TIME ZONE,
    revoked       BOOLEAN                  NOT NULL
);

-- Audit trail (also written to the structured log). Old rows are pruned by a scheduled job.
CREATE TABLE audit_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_type   VARCHAR(16)              NOT NULL,
    actor        VARCHAR(128)             NOT NULL,
    action       VARCHAR(48)              NOT NULL,
    target       VARCHAR(256),
    outcome      VARCHAR(16)              NOT NULL,
    source_ip    VARCHAR(64),
    detail       VARCHAR(512)
);

CREATE INDEX audit_events_occurred_at_idx ON audit_events (occurred_at);
